import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const args = process.argv.slice(2);
const write = args.includes('--write');
const check = args.includes('--check');
const rootArgIndex = args.indexOf('--workspace-root');
const workspaceRoot = rootArgIndex >= 0
  ? path.resolve(args[rootArgIndex + 1] ?? '..')
  : path.resolve(process.cwd(), '..');
const projectRoot = process.cwd();
const outputPath = path.join(projectRoot, 'src/modules/system-handbook/data/generatedSourceSnapshot.ts');

const read = (relativePath) => {
  const absolutePath = path.join(workspaceRoot, relativePath);
  if (!fs.existsSync(absolutePath)) throw new Error(`Missing handbook source: ${relativePath}`);
  return fs.readFileSync(absolutePath, 'utf8');
};

const contract = JSON.parse(read('backend_delivery/docs/platform/system/api/http-contract.json'));
const serviceCatalog = read('backend_delivery/docs/platform/system/service-catalog.md');
const productOverview = read('backend_delivery/docs/platform/product/overview.md');

const classify = (operation) => {
  if (operation.path.includes('/internal')) return 'internal';
  if (operation.service === 'simulator-service') return 'dev-only';
  if (['analytics-service', 'livestream-service'].includes(operation.service)) return 'experimental';
  if (['promotion-service', 'flashsale-service'].includes(operation.service)) return 'gated';
  return 'catalog';
};

const operations = contract.operations.filter((operation) => {
  // Push-token registration is an implementation detail of the notification
  // client, not a public platform contract. Keep it out of the handbook's
  // source snapshot so the public catalog cannot imply support for it.
  return !operation.path.includes('/firebase');
}).map((operation) => {
  const classification = classify(operation);
  return {
    id: operation.id,
    service: operation.service,
    controller: operation.controller,
    handler: operation.handler,
    verbs: operation.verbs,
    path: classification === 'internal' || classification === 'dev-only' ? null : operation.path,
    classification,
  };
});

const snapshot = {
  generatedAt: new Date().toISOString().slice(0, 10),
  sourceRefs: [
    'backend_delivery/docs/platform/product/overview.md',
    'backend_delivery/docs/platform/system/service-catalog.md',
    'backend_delivery/docs/platform/system/api/http-contract.json',
  ],
  counts: {
    operations: operations.length,
    services: new Set(operations.map((operation) => operation.service)).size,
    contractSourceSchemas: contract.counts?.sourceSchemas ?? 0,
    documentedServiceRows: (serviceCatalog.match(/^\| `[^`]+`/gm) ?? []).length,
    productProjects: (productOverview.match(/^### `[^`]+`/gm) ?? []).length,
  },
  operations,
};

const contents = `// Generated by scripts/generate-system-handbook.mjs. Do not edit by hand.\nexport const HANDBOOK_SOURCE_SNAPSHOT = ${JSON.stringify(snapshot, null, 2)} as const;\n`;

if (check) {
  if (!fs.existsSync(outputPath)) throw new Error(`Missing generated handbook snapshot: ${outputPath}`);
  const current = fs.readFileSync(outputPath, 'utf8');
  if (current !== contents) {
    throw new Error('System handbook source snapshot is stale. Run with --write.');
  }
  console.log(`System handbook snapshot is current (${snapshot.counts.operations} operations).`);
} else if (write) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, contents);
  console.log(`Generated ${path.relative(projectRoot, outputPath)} (${snapshot.counts.operations} operations).`);
} else {
  console.log('Use --write to generate or --check to validate the system handbook snapshot.');
}
